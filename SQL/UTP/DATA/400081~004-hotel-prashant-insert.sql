     address/phone but did not establish a Zomato or Swiggy partnership. So,
     same as before, only self-delivery (Rs 300 minimum, by phone) is
     recorded in restaurant_delivery; no restaurant_delivery_provider rows
     are added. This is now a verified absence, not just an unmentioned one.
   - 'LUNCH' itself is a priced combo item (Rs 220: dal fry, punjabi bhaji,
     paneer bhaji, raita, papad, pickle, jeera rice or pulav, 2 roti or 2
     punjabi puri, sweet) -- modeled like the Sizzlers, as one item with the
     component list in its description.

   IMPORTANT -- DUPLICATE-DATA RISK:
   If the earlier docx-based Prashant Family Restaurant script has ALREADY
   been run against your database, running this script too will create a
   SECOND, separate restaurant/establishment row (this script only knows how
   to insert a new restaurant -- it does not look for or remove the old
   one). If the earlier script was already applied, tell me and I will
   write a companion script that removes that restaurant's data first --
   this schema has no ON DELETE CASCADE on these foreign keys, so that
   needs an explicit, correctly-ordered set of deletes across every
   dependent table, which I did not want to guess at without confirming
   that's actually needed.
   ============================================================================ */
