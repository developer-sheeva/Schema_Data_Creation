     pages, independently re-transcribed -- not a re-run of the old docx.
     Category boundaries, a handful of item names, and quite a few prices
     differ in minor ways from the docx version (e.g. Special Punjabi Dishes
     is a completely different 15-item list here, vs 3 items before). This
     script does not attempt to reconcile the two -- it reflects the JSON only.
   - The 28 items that had no price in the docx (19 Tandoor breads, 9 Lunch
