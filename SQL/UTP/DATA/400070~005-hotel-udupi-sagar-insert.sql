/* ============================================================================
   KHAUSTAN -- RESTAURANT ONBOARDING: Hotel Udupi Sagar
   Source: Hotel_Udupi_Sagar_Menu_Transcription.docx  (docx-menu -> Postgres pipeline)
   Target: KhaustanRestaurantMenu database.

   SCOPE NOTES -- read before running:
   - Same ID convention: this script uses the fixed restaurant/source namespace requested for
     Hotel Udupi Sagar: establishment_id = restaurant_id = source_id = 400070005.
     Menu-specific IDs begin at 400070005001 independently for categories, items,
     variants, prices, and board items.
   - No address is given anywhere in the source document -- not even a locality
     or PIN code, only a name, a phone number and a tagline. address_line1/2,
     locality and postal_code are left NULL (all nullable in this schema).
     city/state/country_code are left to their schema defaults (Mumbai /
     Maharashtra / IN) rather than asserted as extracted fact. Please supply the
     real address and I'll add it.
   - No delivery information appears anywhere in this menu (no home-delivery
     section, no minimum order, unlike Prashant Family Restaurant's docx) -- so,
     unlike that script, this one does NOT touch restaurant_delivery or
     delivery_provider/restaurant_delivery_provider at all. Delivery capability
     is left completely unestablished rather than asserted either way.
   - service_mode: only 'dine_in' is linked. The menu's own structure (soups,
     appetizers, thali, multi-course mains) is a sit-down menu; nothing in the
     source specifically evidences takeaway, delivery, or bulk/catering the way
     Prashant Family Restaurant's docx did, so those are left unlinked rather
     than assumed.
   - 7 dishes are printed as one line marked '(DR & GR)' -- Dry or Gravy -- at a
     single shared price (Mushroom Manchurian, Paneer 65, Gobi Manchurian,
     Mushroom Chilly, Paneer Manchurian, Paneer Chilly, Paneer Schezwan). Each
     is modeled as ONE menu_item with TWO variants (Dry / Gravy), both at the
     printed price, rather than two separate items -- unlike the Half/Full rice
     items, which the source numbers and prices as genuinely separate lines and
     so are kept as separate menu_items, matching how Half/Full was handled for
     Prashant Family Restaurant.
   - 'Cold Drink' and 'Packaged Water' are printed as 'MRP' (no fixed price --
     Indian shorthand for 'whatever's printed on the bottle'). These use
     is_market_price = TRUE with a NULL price_amount, which is a materially
     different situation from Prashant Family Restaurant's 28 no-price items:
     those were fixed-price dishes simply missing a number in the source, where
     is_market_price would have mis-described them; these two genuinely are
     variable by design.
   - No 'JAIN' marking appears anywhere in this source, so is_jain is left NULL
     for every item (vs. 3 items flagged for Prashant Family Restaurant).
   - canonical_dish is left NULL throughout, same reasoning as before: it's a
     cross-restaurant identity list that needs visibility this session doesn't
     have.
   - The source numbers items 1-286 with several irregularities that don't
     reflect missing data: number 88 and 169 are simply skipped, numbers
     215-238 are skipped between Rice and Manchurian with no textual gap, item
     184 is used twice (Cheese Naan / Garlic Naan), and Kaju Korma/Paneer/Dingri
     are numbered 293-295 despite sitting physically among the 120s. None of
     this affects the data below -- menu_item doesn't store the source's own
     item numbers -- but it's worth knowing if you cross-check against the
     original.
   - Worth a second look before publishing: 'Cheese Garlic Naan' is printed at
     Rs 15, cheaper than either 'Cheese Naan' or 'Garlic Naan' alone (Rs 70
     each) -- possibly a typo for 115 or 150 in the source. Transcribed exactly
     as printed.
   ============================================================================ */

